    private val httpClient = OkHttpClient.Builder()
        .connectTimeout(5, TimeUnit.SECONDS)
        .readTimeout(5, TimeUnit.SECONDS)
        .build()

    suspend fun fetchRemoteIps(isIpv6: Boolean): List<String> = withContext(Dispatchers.IO) {
        val url = if (isIpv6) {
            "https://www.baipiao.eu.org/cloudflare/ips-v6"
        } else {
            "https://www.baipiao.eu.org/cloudflare/ips-v4"
        }
        try {
            val request = Request.Builder().url(url).build()
            httpClient.newCall(request).execute().use { response ->
                if (response.isSuccessful) {
                    val body = response.body?.string()
                    if (!body.isNullOrEmpty()) {
                        val lines = body.lines()
                            .map { it.trim() }
                            .filter { it.isNotEmpty() && !it.startsWith("#") }
                        if (lines.isNotEmpty()) return@withContext lines
                    }
                }
            }
        } catch (e: Exception) {
            // Fallback to default CIDRs
        }
        return@withContext if (isIpv6) DEFAULT_IPV6_CIDRS else DEFAULT_IPV4_CIDRS
    }
